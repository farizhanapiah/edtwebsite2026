-- EDT — one-time Supabase setup.
-- Run this in the Supabase dashboard → SQL Editor.
-- Then create two Storage buckets in the UI:
--   decks  → Public
--   cvs    → Private
-- And create your team login(s) under Authentication → Users.

-- Pitch decks (uploader) -----------------------------------------------------
-- Named `deck_uploads` to avoid colliding with any pre-existing `decks` table.
create table if not exists deck_uploads (
  id uuid primary key default gen_random_uuid(),
  slug text unique not null,            -- used in the public /d/<slug> link
  title text not null,
  client_name text,
  file_path text not null,              -- path inside the 'decks' storage bucket
  created_at timestamptz default now(),
  created_by uuid references auth.users(id)
);

-- Talent applications --------------------------------------------------------
create table if not exists applications (
  id uuid primary key default gen_random_uuid(),
  applicant_type text not null check (applicant_type in ('intern','full-time')),
  full_name text not null,
  email text not null,
  phone text,
  role_interest text,                   -- position / discipline of interest
  profile text,                         -- personal profile / bio
  portfolio_url text not null,          -- REQUIRED
  linkedin_url text,
  cv_path text,                         -- path inside the private 'cvs' bucket
  source text,                          -- "how did you find EDT"
  notes text,                           -- "anything else"
  availability text,                    -- earliest start / availability
  created_at timestamptz default now()
);

-- Lock down direct (anon-key) access. All reads/writes go through server
-- routes using the service-role key, which bypasses RLS. With RLS enabled and
-- no policies, the public anon key gets default-deny — the secure default.
alter table deck_uploads enable row level security;
alter table applications enable row level security;

-- Blog posts (uploader) ------------------------------------------------------
-- Also create a Storage bucket in the UI:
--   blog   → Public   (post HTML + cover/share images; paths contain random
--                      tokens, so draft files can't be guessed)
create table if not exists blog_posts (
  id uuid primary key,                  -- generated by the upload route
  slug text unique not null,            -- public URL: /blog/<slug>
  title text not null,
  excerpt text,                         -- shown on blog cards
  category text not null check (category in ('Guides','Case Studies','Products','Insights')),
  status text not null default 'draft' check (status in ('draft','published')),
  published_at timestamptz not null default now(), -- future date = scheduled
  file_path text not null,              -- post HTML inside the 'blog' bucket
  cover_path text,                      -- cover image inside the 'blog' bucket
  og_image_path text,                   -- optional share image (falls back to cover)
  seo_title text,
  seo_description text,
  read_minutes int,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  created_by uuid references auth.users(id)
);

create index if not exists blog_posts_live_idx on blog_posts (status, published_at desc);

alter table blog_posts enable row level security;

-- Added later: point a post's canonical URL at an existing page (e.g. a blog
-- copy of a /work case study) so Google doesn't treat it as duplicate content.
alter table blog_posts add column if not exists canonical_path text;
